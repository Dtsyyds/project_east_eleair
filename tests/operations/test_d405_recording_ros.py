"""Real recorder + vision service, isolated synthetic streams; no device launch."""
import json
import os
from pathlib import Path
import threading
import time

import numpy as np
import pytest
import yaml

from inspection_runtime.paths import project_root
from test_operations import request


@pytest.mark.skipif(os.environ.get('ROS_DOMAIN_ID') != '187' or os.environ.get('ROS_LOCALHOST_ONLY') != '1',
                    reason='explicit isolated ROS domain 187 required')
def test_d405_only_mcap_and_sample_with_other_topics_present(tmp_path):
    import rclpy
    import rosbag2_py
    from rclpy.node import Node
    from rclpy.executors import MultiThreadedExecutor
    from rclpy.qos import qos_profile_sensor_data, QoSProfile, ReliabilityPolicy, DurabilityPolicy
    from rclpy.serialization import deserialize_message
    from sensor_msgs.msg import Image, CameraInfo
    from realsense2_camera_msgs.msg import Extrinsics
    from std_msgs.msg import String
    from inspection_operations.operations_node import OperationsNode
    from d405_seam_tracking.cli import synthetic_frame
    from d405_seam_tracking.dataset import load_index, read_sample

    root = project_root()
    config = yaml.safe_load((root / 'config/communication/d405_experiment.yaml').read_text())
    config['data_root'] = str(tmp_path)
    config['minimum_free_bytes'] = 1
    rclpy.init()
    fixture = Node('d405_only_synthetic_fixture')
    pubs = {}
    for topic in config['record_topics']:
        if not topic.startswith('/d405/camera/'):
            continue  # Results are generated by the real algorithm process.
        kind = CameraInfo if topic.endswith('/camera_info') else Extrinsics if '/extrinsics/' in topic else Image
        qos = (QoSProfile(depth=1, reliability=ReliabilityPolicy.RELIABLE, durability=DurabilityPolicy.TRANSIENT_LOCAL)
               if kind == Extrinsics else qos_profile_sensor_data)
        pubs[topic] = fixture.create_publisher(kind, topic, qos)
    unrelated = ['/camera/front/image_raw', '/camera/fisheye/image_raw', '/inspection/emat/result', '/eddy/data', '/robot/state']
    noise = {topic: fixture.create_publisher(String, topic, 10) for topic in unrelated}
    ticks = [0]
    sent_stamps = set()
    def publish():
        ticks[0] += 1
        frame = synthetic_frame(stamp=time.time_ns(), sequence=ticks[0])
        h, w = frame.image.shape
        sent_stamps.add(frame.image_stamp_ns)
        rgb = Image()
        rgb.header.frame_id = 'synthetic_d405_optical_frame'
        rgb.header.stamp.sec, rgb.header.stamp.nanosec = divmod(frame.image_stamp_ns, 1_000_000_000)
        rgb.width, rgb.height, rgb.encoding, rgb.step = w, h, 'rgb8', w * 3
        rgb.data = np.repeat(frame.image[:, :, None], 3, axis=2).tobytes()
        depth = Image()
        depth.header = rgb.header
        depth.width, depth.height, depth.encoding, depth.step = w, h, '16UC1', w * 2
        depth.data = frame.depth.tobytes()
        ir = Image()
        ir.header = rgb.header
        ir.width, ir.height, ir.encoding, ir.step = w, h, 'mono8', w
        ir.data = frame.image.tobytes()
        info = CameraInfo()
        info.header = rgb.header
        info.width, info.height = w, h
        info.k = [float(v) for v in frame.image_calibration.k]
        info.distortion_model = 'none'
        extrinsics = Extrinsics()
        extrinsics.rotation = np.eye(3).ravel(order='F').tolist()
        extrinsics.translation = [0., 0., 0.]
        for topic, pub in pubs.items():
            if '/extrinsics/' in topic and ticks[0] > 1:
                continue  # Real driver calibration can precede recorder startup.
            msg = (info if topic.endswith('/camera_info') else extrinsics if '/extrinsics/' in topic
                   else depth if '/depth/' in topic else ir if '/infra' in topic else rgb)
            pub.publish(msg)
        for pub in noise.values():
            pub.publish(String(data='UNRELATED SYNTHETIC DATA: MUST NOT BE RECORDED'))
    fixture.create_timer(.1, publish)
    node = OperationsNode(config)
    assert node.operations.camera_operation is None
    # Test-only mount substitution; never weaken the application's real guard.
    mounted = lambda: {'mounted': True, 'free_bytes': 10**10}
    node.operations.storage = mounted
    node.operations.vision.storage = mounted
    events = []
    node.operations.emit = events.append
    executor = MultiThreadedExecutor(num_threads=2)
    executor.add_node(node)
    executor.add_node(fixture)
    thread = threading.Thread(target=executor.spin, daemon=True)
    thread.start()
    def wait(predicate, timeout=35):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if predicate():
                return
            time.sleep(.05)
        raise AssertionError('timed out: ' + json.dumps(events[-3:], ensure_ascii=False))
    def action(name, ident, **parameters):
        node.operations.handle(request(name, ident, **parameters))
        def results():
            return [e['payload'] for e in events if e['payload'].get('request_id') == ident
                    and e['payload'].get('status') in ('completed', 'failed')]
        wait(results)
        assert results()[-1]['status'] == 'completed', results()[-1]
        return results()[-1]
    try:
        wait(lambda: all(t in node.operations.live_topics() for t in config['required_topics']))
        action('collection.preflight', 'preflight')
        action('vision.start', 'vision-start')
        action('collection.start', 'record-start', profile='d405_experiment')
        start_tick = ticks[0]
        wait(lambda: ticks[0] >= start_tick + 30)
        saved = action('vision.save_sample', 'save')
        session = Path(saved['vision']['directory'])
        sample_root, index = load_index(session / 'index.json')
        raw = read_sample(sample_root, index['samples'][0])
        assert raw.depth is not None and raw.source['stream'] == 'color'
        run = node.operations.run_dir
        refs = list((session / 'samples').glob('event_*/collection_reference.json'))
        assert len(refs) == 1
        assert json.loads(refs[0].read_text())['run_id'] == run.name
        action('collection.stop', 'record-stop', run_id=run.name)
        assert node.operations.task['complete'] is True
        assert node.operations.vision.snapshot()['status'] == 'running'
        action('vision.stop', 'vision-stop')
        tick = ticks[0]
        wait(lambda: ticks[0] > tick + 2)
        record = json.loads((run / 'run.json').read_text())
        assert set(record['topic_counts']) == set(config['record_topics'])
        assert all(count > 0 for count in record['topic_counts'].values())
        assert not set(unrelated).intersection(record['topic_counts'])
        reader = rosbag2_py.SequentialReader()
        reader.open(rosbag2_py.StorageOptions(uri=str(run / 'bag'), storage_id='mcap'), rosbag2_py.ConverterOptions('', ''))
        checked = set()
        while reader.has_next():
            topic, data, _ = reader.read_next()
            assert topic in config['record_topics']
            if topic in config['required_topics']:
                image = deserialize_message(data, Image)
                stamp = image.header.stamp.sec * 1_000_000_000 + image.header.stamp.nanosec
                assert stamp in sent_stamps
                assert len(image.data) == image.height * image.step
                assert image.header.frame_id == 'synthetic_d405_optical_frame'
                checked.add(topic)
        assert checked == set(config['required_topics'])
        evidence = root / '.runtime/s100p/validation/d405_profile'
        evidence.mkdir(parents=True, exist_ok=True)
        (evidence / 'ros-recording.json').write_text(json.dumps({
            'synthetic_input': True, 'hardware_acceptance': False, 'ros_domain_id': 187,
            'localhost_only': True, 'run': record, 'sample_session': str(session),
            'excluded_published_topics': unrelated, 'source_timestamps_verified': sorted(checked),
            'camera_continued_after_vision_stop': True,
        }, ensure_ascii=False, indent=2))
    finally:
        node.operations.close()
        executor.shutdown()
        thread.join(timeout=5)
        node.destroy_node()
        fixture.destroy_node()
        rclpy.shutdown()
